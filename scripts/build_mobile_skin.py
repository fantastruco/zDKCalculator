"""Create the mobile skin's normal/hover/active vector masters and resource map."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'asset' / 'ui'
OUT = BASE / 'mobile'
NS = 'http://www.w3.org/2000/svg'
ET.register_namespace('', NS)

SKINS = [
    ('Header', 'header-wide', 2),
    ('Panel', 'panel-main', 2),
    ('Button', 'button-compact', 3),
    ('Action', 'button-ornate', 3),
    ('Tab', 'button-chevron', 3),
    ('Field', 'button-slim', 3),
    ('Effect', 'button-capped', 3),
    ('Section', 'banner-section', 2),
    ('Reticle', 'orb-reticle', 3),
    ('Sparkle', 'sparkle-diamond', 3),
    ('Progress', 'progress-arrow', 3),
    ('Divider', 'divider-notch', 2),
    ('Card', 'panel-compact-glow', 3),
    ('Toggle', 'slot-diagonal', 3),
]


def make_variant(asset, kind, state):
    tree = ET.parse(BASE / asset['svg'])
    root = tree.getroot()
    by_id = {node.get('id'): node for node in root.iter() if node.get('id')}
    title = root.find(f'{{{NS}}}title')
    title.text = f'{asset["name"]} — mobile {state}'
    colors = {'normal': '#d91b6d', 'hover': '#ff479c', 'active': '#ff79bd'}
    for node in root.iter():
        if node.get('stroke') in ('#ff087a', '#ff539f'):
            node.set('stroke', colors[state])
    if 'glow-layer' in by_id:
        by_id['glow-layer'].set('opacity', {'normal': '.22', 'hover': '.75', 'active': '.98'}[state])
    if 'glow' in by_id:
        blur = by_id['glow'].find(f'{{{NS}}}feGaussianBlur')
        blur.set('stdDeviation', {'normal': '1', 'hover': '1.8', 'active': '2.3'}[state])
    if 'outline' in by_id:
        by_id['outline'].set('opacity', '1')
        for node in by_id['outline']:
            node.set('stroke-opacity', {'normal': '.70', 'hover': '.95', 'active': '1'}[state])
    if 'accents' in by_id:
        by_id['accents'].set('opacity', {'normal': '.60', 'hover': '.85', 'active': '1'}[state])
    if 'texture' in by_id:
        by_id['texture'].set('opacity', '.24' if kind == 'Panel' else '.50')
    if 'body' in by_id:
        for stop in by_id['body']:
            center = stop.get('offset') in ('.30', '.70')
            opacity = ('.79' if center else '.90') if kind == 'Panel' else '.96'
            stop.set('stop-opacity', opacity)
            if state == 'active' and kind not in ('Panel', 'Header'):
                stop.set('stop-color', '#23091b' if center else '#670d39')
    if state == 'active' and kind in ('Tab', 'Action', 'Button', 'Card'):
        glow = ET.SubElement(root, f'{{{NS}}}g', {'id': 'selection-light', 'clip-path': 'url(#bodyClip)', 'opacity': '.16'})
        ET.SubElement(glow, f'{{{NS}}}rect', {'width': str(asset['width']), 'height': str(asset['height']), 'fill': 'url(#fill)'})
    path = OUT / 'svg' / state / (asset['id'] + '.svg')
    path.parent.mkdir(parents=True, exist_ok=True)
    content = ET.tostring(root, encoding='utf-8', xml_declaration=True)
    if not path.exists() or path.read_bytes() != content:
        path.write_bytes(content)
    return path.relative_to(OUT).as_posix()


def main():
    catalog = json.loads((BASE / 'catalog.json').read_text())
    assets = {a['id']: a for a in catalog['assets']}
    records = []
    resource_id = 200
    rc = ['// Generated by scripts/build_mobile_skin.py.']
    header = ['#pragma once', '// Generated mobile skin resource definitions.', 'namespace zDKUI {',
              'enum class zDKUISkinKind { ' + ', '.join('zDKUI' + ('EffectRow' if s[0] == 'Effect' else s[0]) for s in SKINS) + ', zDKUICount };',
              'struct zDKUISkinDefinition { int zDKUIWidth,zDKUIHeight,zDKUILeft,zDKUITop,zDKUIRight,zDKUIBottom; int zDKUIResource[3]; };',
              'inline constexpr zDKUISkinDefinition zDKUISkinDefinitions[] = {']
    for kind, slug, scale in SKINS:
        asset = assets[slug]
        ids = []
        for state in ('normal', 'hover', 'active'):
            svg = make_variant(asset, kind, state)
            png = f'png/{state}/{slug}.png'
            records.append({'id': slug, 'kind': kind, 'state': state, 'svg': svg, 'png': png,
                            'width': asset['width'], 'height': asset['height'], 'scale': scale,
                            'resource': resource_id})
            rc.append(f'{resource_id} RCDATA "../asset/ui/mobile/{png}"')
            ids.append(resource_id)
            resource_id += 1
        inset = asset['stretch_insets'] or [0, 0, 0, 0]
        header.append('    {' + ','.join(str(n) for n in [asset['width'], asset['height'], *inset])
                      + ', {' + ','.join(map(str, ids)) + '}}, // ' + kind)
    header += ['};', '} // namespace zDKUI', '']
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'catalog.json').write_text(json.dumps(records, indent=2) + '\n')
    (ROOT / 'src' / 'zDKUIAssets.h').write_text('\n'.join(header))
    (ROOT / 'src' / 'zDKUIAssets.rcinc').write_text('\n'.join(rc) + '\n')
    print(f'Generated {len(records)} mobile SVG states and the C++/RC resource map.')


if __name__ == '__main__':
    main()
